-- 바깥 요청에 「무엇으로, 어디로」를 더한다.
--
-- action_logs 에 컬럼 둘을 더한다. 있는 컬럼은 건드리지 않는다.
--
--   method  GET, POST 같은 요청 방식.
--   url     실제로 보낸 주소.
--
-- 왜 더하는가. 지금까지 바깥 요청에 남는 것은 이름(「카카오 지도」)과
-- 무엇을 하려고 불렀나(「지도 띄우기」)뿐이었다. 그 둘만으로는 어느 자리로
-- 보낸 요청인지 알 수 없어, 느리거나 물린 로우를 찾아도 어디를 들여다봐야
-- 할지 알 길이 없었다.
--
-- **열쇠는 적지 않는다.** 주소를 적는 쪽이 물음표 앞까지만 넘긴다
-- (app/routers/action_logs.py 의 바깥적기, frontend/src/utils/track.ts).
-- 서비스 열쇠가 기록에 쌓이면 관리자 사이트를 여는 사람이 그 값을 그대로
-- 읽게 된다.
--
-- 이미 쌓인 로우는 비어 있다. 지난 로우를 되살릴 길은 없으므로 NULL 로 두고,
-- 화면은 그 자리에 줄표를 적는다.
--
-- 300자로 잡은 까닭: 공휴일 요청이 물음표 뒤까지 쳐서 120자쯤이고, 지도
-- SDK 가 40자다. 길 쪽이 늘어날 여지를 두되 무한정 받지는 않는다.

BEGIN;

ALTER TABLE life_expense.action_logs
    ADD COLUMN IF NOT EXISTS method varchar(10);

ALTER TABLE life_expense.action_logs
    ADD COLUMN IF NOT EXISTS url varchar(300);

COMMIT;

