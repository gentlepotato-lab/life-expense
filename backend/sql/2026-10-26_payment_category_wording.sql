-- 결제 수단 구분 이름을 통상 쓰는 말로 맞춘다.
--
-- `계좌·현금`을 `현금`으로 바꾼다. 까닭은 둘이다.
--
--   - 가운뎃점을 쓰지 않는다(life/expense/CLAUDE.md의 문서 작성 규칙).
--   - 현금과 계좌이체를 묶어 부르는 통상 표현이 `현금`이다. 국세청도
--     현금영수증 제도에서 계좌이체와 무통장입금을 현금거래로 묶는다.
--     카드, 현금, 간편결제로 가르는 것이 가계부와 POS 쪽에서 쓰는 꼴이다.
--
-- 한 로우만 고친다. name에 UNIQUE가 걸려 있어 같은 이름이 둘일 수 없고,
-- `현금`이라는 이름은 아직 없다. 스키마의 글자 컬럼 81개를 훑어 바꾸려는
-- 값이 담긴 자리가 payment_method_categories.name 하나뿐인 것을 확인했다.
-- 결제 수단은 category_id로 가리키므로 이름이 바뀌어도 끊기지 않는다.
--
-- 이 구분에 달린 결제 수단은 `현금/계좌이체`다. 구분이 `현금`이면 묶음
-- 머리말과 그 아래 한 줄이 서로 다른 말로 서서 어느 쪽이 구분인지 읽힌다.
--
-- 담긴 값만 바뀌고 테이블 꼴은 그대로다. ALTER는 한 줄도 없다.

BEGIN;

UPDATE life_expense.payment_method_categories
   SET name = '현금'
     , updated_at = now()
 WHERE name = '계좌·현금';

COMMIT;

