/**
 * 종 — 잔소리를 부르는 단추의 그림.
 *
 * 홈의 잔소리 그림(HomeArt의 ArtNudge)과 같은 종이다. 위에 꼭지가 있고,
 * 아래로 벌어진 자락이 테두리에서 딱 끊긴 뒤 추가 달린다.
 * 옆에 선 새로 고침 · 계산기와 선 두께를 맞췄다(24 상자에 2).
 * 빛깔은 currentColor라 부르는 쪽 글자색을 따라간다.
 *
 * 상자는 옆 단추들보다 한 단 크다(18 → 20). 종만 상자 안에서 0.82로 줄여
 * 소리 자리를 냈기 때문에, 같은 18로 두면 그려진 키가 12.2px밖에 되지 않아
 * 새로 고침(13.5) · 계산기(15) · 붓(17.9) 옆에서 유독 작아 보였다.
 *
 * 홈 그림과 같이 방금 흔들린 모습이다 — 몸통을 13도 눕히고 추를 그 방향으로
 * 따라 내보내고, 양옆에 짧은 소리 선을 하나씩 둔다. 소리 선은 몸통보다
 * 가늘고 옅어(1.8 두께 · 55%) 18px에서도 몸통과 다투지 않는다.
 */
export default function BellIcon({ size = 20 }: { size?: number }) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {/* 종은 상자를 가득 채우고 있어, 눕히면 오른쪽 자락이 상자를 넘어 잘린다.
          0.82로 줄여 양옆에 소리가 설 자리를 낸다. 줄인 만큼 선을 굵게 그려
          (2 ÷ 0.82) 그려진 두께는 옆의 새로 고침 · 계산기와 같은 2로 남는다. */}
      <g transform="translate(12 12.6) scale(0.82) translate(-12 -12)" strokeWidth={2.44}>
        {/* 몸통과 꼭지 — 종의 한가운데를 축으로 함께 눕는다. 꼭지를 축으로
            돌리면 아래가 크게 쓸려 나가 상자를 넘는다. */}
        <g transform="rotate(-13 12 11)">
          <path d="M12 2.2v2" />
          <path d="M18.4 10.6c0-3.5-2.9-6.4-6.4-6.4s-6.4 2.9-6.4 6.4c0 4.4-1.6 6.4-2.8 7.6h18.4c-1.2-1.2-2.8-3.2-2.8-7.6Z" />
        </g>
        {/* 추 — 몸통을 따라 나가지만 함께 돌지는 않는다. 매달린 것이라
            제 방향으로 흐른다. */}
        <path d="M11.1 20.9a2.2 2.2 0 0 0 4.1-.5" />
      </g>
      {/* 소리 — 양옆으로 짧게. 가늘고 옅게 두어 몸통을 가리지 않는다.
          오른쪽 위는 알림 딱지가 덮으므로 그 아래로 내려 그린다. */}
      <g opacity="0.55" strokeWidth={1.8}>
        <path d="M2.2 10.4a4.6 4.6 0 0 0-.4 5.2" />
        <path d="M21.8 8.6a4.6 4.6 0 0 1 .5 5.2" />
      </g>
    </svg>
  );
}
